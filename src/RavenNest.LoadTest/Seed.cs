using System.Data.SqlClient;
using System.Text;
using RavenNest.BusinessLogic.Game;

namespace RavenNest.LoadTest;

/// <summary>
/// Creates the test streamer account(s). The server has no way to create a user with a password
/// without a Twitch sign in (players are created by joining, but a streamer needs a password to
/// sign in from the game), so this is the one step that goes to the database directly.
///
/// It writes an idempotent SQL script. Run it with the server STOPPED, then start the server: the
/// server loads every row into memory at startup and only sees rows that were there then.
/// </summary>
public static class Seed
{
    public static async Task<int> RunAsync(Options o)
    {
        if (string.IsNullOrEmpty(o.Password))
        {
            Console.Error.WriteLine("seed: no password. Set " + Options.PasswordEnv + " (or --password) to the password the test streamer(s) should have.");
            return 1;
        }

        // the server's own hasher, so the hash is whatever AuthManager.Authenticate compares against
        var hash = new SecureHasher().Get(o.Password);
        var names = Enumerable.Range(0, o.Sessions).Select(o.StreamerNameFor).ToList();
        var sql = BuildSql(names, hash);
        await File.WriteAllTextAsync(o.SeedOut, sql);
        Console.WriteLine("Wrote " + Path.GetFullPath(o.SeedOut) + " for: " + string.Join(", ", names));

        if (!o.Execute)
        {
            Console.WriteLine("Run it against the DEV database with the server stopped, then start the server.");
            Console.WriteLine("Or run this again with --execute and the connection string in " + Options.DbEnv + ".");
            return 0;
        }

        var connectionString = Environment.GetEnvironmentVariable(Options.DbEnv);
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            Console.Error.WriteLine("seed --execute: set " + Options.DbEnv + " to the dev database connection string.");
            return 1;
        }

        if (IsPortOpen(o.EffectiveTcpHost, o.EventPort))
        {
            Console.WriteLine("Note: something is listening on port " + o.EventPort + ". If that is the RavenNest server, it will not see the new account until it is restarted.");
        }

        try
        {
            using var connection = new SqlConnection(connectionString);
            await connection.OpenAsync();
            using var cmd = connection.CreateCommand();
            cmd.CommandText = sql;
            await cmd.ExecuteNonQueryAsync();
            Console.WriteLine("Seed applied. Start (or restart) the server before running the load test.");
            return 0;
        }
        catch (SqlException exc)
        {
            Console.Error.WriteLine("seed --execute failed: " + exc.Message);
            return 1;
        }
    }

    public static string BuildSql(IReadOnlyList<string> streamerNames, string passwordHash)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- RavenNest load test: test streamer accounts. Generated by RavenNest.LoadTest seed.");
        sb.AppendLine("--");
        sb.AppendLine("-- DEV DATABASE ONLY. Run with the RavenNest server stopped, then start it: the server keeps");
        sb.AppendLine("-- every row in memory and only knows rows that existed when it started.");
        sb.AppendLine("--");
        sb.AppendLine("-- Creates each user with a password (and an empty Resources row, as the server does for new");
        sb.AppendLine("-- users), hidden from the highscore, no Twitch link. Running it again only resets the password.");
        sb.AppendLine("-- The simulated players are NOT created here: the load test creates them through the server's");
        sb.AppendLine("-- own join path (POST api/players), which makes a user and a character for an unknown player.");
        sb.AppendLine();
        sb.AppendLine("SET NOCOUNT ON;");
        sb.AppendLine("SET XACT_ABORT ON;");
        sb.AppendLine("BEGIN TRANSACTION;");
        sb.AppendLine();

        for (var i = 0; i < streamerNames.Count; ++i)
        {
            var name = Sql(streamerNames[i]);
            var hash = Sql(passwordHash);
            sb.AppendLine($"IF NOT EXISTS (SELECT 1 FROM [User] WHERE [UserName] = N'{name}')");
            sb.AppendLine("BEGIN");
            sb.AppendLine($"    DECLARE @Resources{i} uniqueidentifier = NEWID();");
            sb.AppendLine($"    INSERT INTO [Resources] ([Id], [Wood], [Ore], [Fish], [Wheat], [Magic], [Arrows], [Coins]) VALUES (@Resources{i}, 0, 0, 0, 0, 0, 0, 0);");
            sb.AppendLine("    INSERT INTO [User] ([Id], [UserId], [UserName], [DisplayName], [PasswordHash], [IsAdmin], [IsModerator], [Status], [IsHiddenInHighscore], [Resources], [Created])");
            sb.AppendLine($"    VALUES (NEWID(), N'loadtest-streamer-{i + 1}', N'{name}', N'{name}', N'{hash}', 0, 0, 0, 1, @Resources{i}, GETUTCDATE());");
            sb.AppendLine("END");
            sb.AppendLine("ELSE");
            sb.AppendLine($"    UPDATE [User] SET [PasswordHash] = N'{hash}' WHERE [UserName] = N'{name}';");
            sb.AppendLine();
        }

        sb.AppendLine("COMMIT TRANSACTION;");
        return sb.ToString();
    }

    private static string Sql(string s) => s.Replace("'", "''");

    private static bool IsPortOpen(string host, int port)
    {
        try
        {
            using var client = new System.Net.Sockets.TcpClient();
            return client.ConnectAsync(host, port).Wait(TimeSpan.FromMilliseconds(500)) && client.Connected;
        }
        catch
        {
            return false;
        }
    }
}
